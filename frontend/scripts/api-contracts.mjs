import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const generated = join(frontend, 'src/generated/api');

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value !== null && typeof value === 'object') {
    if (typeof value.$ref === 'string' && !value.$ref.startsWith('#/')) {
      throw new Error('External references are forbidden in offline contracts');
    }
    return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]));
  }
  return value;
}

export async function renderArtifacts(schema) {
  const normalized = canonical(schema);
  const ast = await openapiTS(structuredClone(normalized), {
    alphabetize: true,
    // A backend default does not make an optional request property required.
    defaultNonNullable: false,
  });
  return {
    'openapi.json': JSON.stringify(normalized, null, 2) + '\n',
    'types.ts': '// Generated by npm run contracts:generate. DO NOT EDIT.\n' + astToString(ast),
  };
}

export async function syncArtifacts(directory, artifacts, check) {
  if (!check) await mkdir(directory, { recursive: true });
  const stale = [];
  for (const [name, expected] of Object.entries(artifacts)) {
    const path = join(directory, name);
    if (!check) {
      await writeFile(path, expected, 'utf8');
      continue;
    }
    let actual;
    try {
      actual = await readFile(path, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (actual !== expected) stale.push(name);
  }
  if (stale.length) {
    throw new Error(`Contract drift: ${stale.join(', ')}. Run make contracts-generate and commit both artifacts.`);
  }
}

async function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) {
    throw new Error('Usage: node scripts/api-contracts.mjs [--check]');
  }
  const document = execFileSync(process.env.PYTHON || 'python3.11', [
    '-I', join(frontend, '../backend/scripts/export_openapi.py'),
  ], { encoding: 'utf8', timeout: 40_000, maxBuffer: 16 * 1024 * 1024 });
  await syncArtifacts(generated, await renderArtifacts(JSON.parse(document)), process.argv.includes('--check'));
  console.log(process.argv.includes('--check') ? 'API contracts are current.' : 'API contracts generated.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
